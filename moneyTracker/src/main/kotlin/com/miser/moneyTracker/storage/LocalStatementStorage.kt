package com.miser.moneyTracker.storage

import org.springframework.beans.factory.annotation.Value
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty
import org.springframework.stereotype.Component
import java.nio.file.Files
import java.nio.file.Path

/** Files under a local directory. Default; good for development and single-host installs. */
@Component
@ConditionalOnProperty(name = ["app.storage.type"], havingValue = "local", matchIfMissing = true)
class LocalStatementStorage(@Value("\${app.upload-dir}") uploadDir: String) : StatementStorage {

    private val root: Path = Path.of(uploadDir).toAbsolutePath().normalize()

    override fun store(userId: Long, filename: String?, content: ByteArray, contentType: String?): String {
        val key = storageKey(userId, filename)
        val target = resolve(key)
        Files.createDirectories(target.parent)
        Files.write(target, content)
        return key
    }

    override fun load(key: String): ByteArray = Files.readAllBytes(resolve(key))

    override fun delete(key: String) {
        Files.deleteIfExists(resolve(key))
    }

    private fun resolve(key: String): Path {
        // Keys are generated by us, but never let one escape the upload root.
        val path = root.resolve(key).normalize()
        require(path.startsWith(root)) { "Invalid storage key" }
        return path
    }
}
